fun main() {
    println("--- BÀI 1: IN CÁC SỐ TỪ 1 ĐẾN 10 ---")
    // for
    print("Dùng for  : ")
    for (i in 1..10) {
        print("$i ")
    }
    println()

    //while:
    print("Dùng while: ")
    var count = 1
    while (count <= 10) {
        print("$count ")
        count++
    }
    println()
}